"""The knowledge-base rows the watcher may never change (2026-10-15).

The KB watcher (kb-admin, stages 1-3) drafts KB changes from public web pages.
A draft may NEVER change an agency fee, a cb_kb_rules value, or a row that came
from the agency's fees document (docs/Minghwee bot fees and process final
structure.docx, applied 2026-10-15). Such a draft is shown as "needs agency
confirmation" and cannot be approved.

This script derives the locked rows FROM the loader, so the list cannot drift
from what was actually loaded:

  questions - every row the fees document added or corrected, plus every
              per-nationality fee and replacement-fee row (_FEE_ROWS);
  needles   - the corrected text of every fees-document TEXT_REPLACEMENT
              (those rows have no question to key on).

It writes kb-admin/lib/watcher/fee-locked.ts, which kb-admin reads (the
lock shown in the review queue). The SQL migration kb_admin_015_watcher.sql
carries the same two lists (the lock enforced in the database), and
kb-admin's self-check fails if the SQL and the TS module disagree.

    python scripts/gen_fee_locked.py           # rewrite the TS module and the SQL arrays
    python scripts/gen_fee_locked.py --check   # exit 1 if the TS module or the SQL is stale

Reads the loader module only: no database, no network.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "kb-admin" / "lib" / "watcher" / "fee-locked.ts"
SQL = ROOT / "scripts" / "sql" / "kb_admin_015_watcher.sql"
FEES_DOC_REASON = "fees document 2026-10-15"


def compute() -> dict[str, list[str]]:
    sys.path.insert(0, str(ROOT / "scripts"))
    sys.path.insert(0, str(ROOT))
    import load_service_notes as loader  # noqa: E402

    questions: set[str] = set(loader._FEES_DOC_QUESTIONS)
    questions |= {
        u["where"]["question"]
        for u in loader.UPDATES
        if str(u.get("reason", "")).startswith(FEES_DOC_REASON) and u["where"].get("question")
    }
    questions |= {r["question"] for r in loader._FEE_ROWS}
    # The two salary rows the fees document added (decision C).
    questions |= {
        r["question"]
        for r in loader.ROWS
        if r.get("section_heading") in ("Employer - Indonesian helper salary", "Employer - Myanmar helper salary")
    }
    needles = sorted(
        {t["new"] for t in loader.TEXT_REPLACEMENTS if str(t.get("reason", "")).startswith(FEES_DOC_REASON)}
    )
    return {"questions": sorted(questions), "needles": needles}


def _sql_lines(values: list[str]) -> str:
    quoted = ["        '" + v.replace("'", "''") + "'" for v in values]
    return ",\n".join(quoted) + ("\n" if quoted else "")


def fill_sql(sql: str, data: dict[str, list[str]]) -> str:
    """The migration with its two marked arrays replaced by the lists."""
    for marker, key in (("FEE_LOCKED_QUESTIONS", "questions"), ("FEE_LOCKED_NEEDLES", "needles")):
        pattern = re.compile(rf"(-- {marker}:BEGIN\n).*?(-- {marker}:END)", re.S)
        if not pattern.search(sql):
            raise SystemExit(f"marker {marker} not found in {SQL.name}")
        sql = pattern.sub(lambda m: m.group(1) + _sql_lines(data[key]) + m.group(2), sql)
    return sql


def main() -> int:
    data = compute()
    text = (
        "// GENERATED by scripts/gen_fee_locked.py from scripts/load_service_notes.py - do not edit.\n"
        "// The knowledge-base rows a watcher draft may never change (the fee lock).\n"
        "// The watcher migration (scripts/sql, 015) carries the same two lists; kb-admin's self-check compares them.\n\n"
        "export const LOCKED_QUESTIONS: readonly string[] = "
        + json.dumps(data["questions"], indent=2, ensure_ascii=False)
        + ";\n\nexport const LOCKED_NEEDLES: readonly string[] = "
        + json.dumps(data["needles"], indent=2, ensure_ascii=False)
        + ";\n"
    )
    sql_now = SQL.read_text(encoding="utf-8")
    sql_new = fill_sql(sql_now, data)
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text or sql_now != sql_new:
            print("FAIL: fee-locked.ts or kb_admin_015_watcher.sql is stale - run scripts/gen_fee_locked.py")
            return 1
        print(f"PASS: fee-locked.ts and the migration match the loader ({len(data['questions'])} questions, "
              f"{len(data['needles'])} needles)")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    SQL.write_text(sql_new, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(data['questions'])} questions, {len(data['needles'])} needles")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
